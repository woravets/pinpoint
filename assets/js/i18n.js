let curLang = localStorage.getItem('pp_lang') || 'th';

function t(key, vars = {}) {
  let str = (I18N[curLang] && I18N[curLang][key]) || I18N.th[key] || key;
  Object.keys(vars).forEach(k => { str = str.replace(`{${k}}`, vars[k]); });
  return str;
}

function applyLanguage() {
  document.documentElement.lang = curLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      el.innerHTML = t(key);
    }
  });
  const langSel = document.getElementById('slang');
  if (langSel) langSel.value = curLang;
  if (typeof renderAll === 'function') renderAll();
  if (typeof renderSettings === 'function') renderSettings();
  if (!getApiKey() && typeof renderNoKeyBanner === 'function') renderNoKeyBanner();
}

function changeLanguage(lang) {
  if (!I18N[lang]) return;
  curLang = lang;
  localStorage.setItem('pp_lang', lang);
  applyLanguage();
  if (typeof toast === 'function') toast(t('toast_lang'), 'ok');
}
